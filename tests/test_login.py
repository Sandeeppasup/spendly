import os

import pytest

import database.db as dbmod
from conftest import fetch_all

DEMO = {"email": "demo@spendly.com", "password": "demo123"}
GENERIC_ERROR = b"Invalid email or password."
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def demo_id():
    return fetch_all("SELECT id FROM users WHERE email = ?", (DEMO["email"],))[0]["id"]


def login(client, **data):
    return client.post("/login", data=data)


def session_user_id(client):
    with client.session_transaction() as s:
        return s.get("user_id")


# ------------------------------------------------------------------ form


def test_get_login_renders_form(client):
    resp = client.get("/login")
    assert resp.status_code == 200
    assert b'action="/login"' in resp.data  # generated by url_for
    assert b'type="password"' in resp.data


def test_login_template_has_no_hardcoded_urls():
    for name in ("login.html", "base.html"):
        with open(os.path.join(ROOT, "templates", name), encoding="utf-8") as f:
            src = f.read()
        assert 'action="/' not in src
        assert 'href="/' not in src


# --------------------------------------------------------------- success


def test_demo_login_redirects_and_sets_session(client):
    resp = login(client, **DEMO)
    assert resp.status_code == 302
    assert resp.headers["Location"].endswith("/profile")
    assert session_user_id(client) == demo_id()


def test_navbar_shows_name_and_sign_out_after_login(client):
    login(client, **DEMO)
    html = client.get("/").data
    assert b"Demo User" in html
    assert b"Sign out" in html
    assert b"Sign in" not in html
    assert b"Get started" not in html


def test_registered_user_can_log_in(client):
    client.post(
        "/register",
        data={"name": "Ann", "email": "ann@example.com", "password": "secret123"},
    )
    resp = login(client, email="ann@example.com", password="secret123")
    assert resp.status_code == 302
    assert session_user_id(client) is not None


def test_email_is_trimmed_and_case_insensitive(client):
    resp = login(client, email="  DEMO@Spendly.com ", password="demo123")
    assert resp.status_code == 302
    assert session_user_id(client) == demo_id()


# --------------------------------------------------------------- failure


def test_wrong_password_and_unknown_email_give_same_error(client):
    wrong_pw = login(client, email=DEMO["email"], password="nope-nope")
    unknown = login(client, email="ghost@example.com", password="demo123")
    for resp in (wrong_pw, unknown):
        assert resp.status_code == 200
        assert GENERIC_ERROR in resp.data
        assert session_user_id(client) is None


def test_failed_login_keeps_email_not_password(client):
    resp = login(client, email="demo@spendly.com", password="wrong-pass")
    assert b'value="demo@spendly.com"' in resp.data
    assert b"wrong-pass" not in resp.data


@pytest.mark.parametrize(
    "data",
    [
        {"email": "", "password": "demo123"},
        {"email": DEMO["email"], "password": ""},
        {"email": "", "password": ""},
        {"email": "   ", "password": "demo123"},
        {},
    ],
)
def test_missing_or_empty_fields_show_error(client, data):
    resp = login(client, **data)
    assert resp.status_code == 200
    assert GENERIC_ERROR in resp.data
    assert session_user_id(client) is None


# --------------------------------------------------------------- session


def test_login_clears_previous_session_data(client):
    with client.session_transaction() as s:
        s["junk"] = "stale"
    login(client, **DEMO)
    with client.session_transaction() as s:
        assert "junk" not in s
        assert set(s.keys()) == {"user_id"}


def test_stale_user_id_is_treated_as_signed_out(client):
    with client.session_transaction() as s:
        s["user_id"] = 99999
    home = client.get("/")
    assert home.status_code == 200
    assert b"Sign in" in home.data
    assert b"Get started" in home.data
    assert client.get("/login").status_code == 200


