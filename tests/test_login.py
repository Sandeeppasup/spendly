# ------------------------------------------------------- already signed in


def test_login_redirects_when_already_signed_in(client):
    login(client, **DEMO)
    resp = client.get("/login")
    assert resp.status_code == 302
    assert resp.headers["Location"].endswith("/profile")
    assert login(client, **DEMO).status_code == 302


def test_register_redirects_when_already_signed_in(client):
    login(client, **DEMO)
    resp = client.get("/register")
    assert resp.status_code == 302
    assert resp.headers["Location"].endswith("/profile")
    before = len(fetch_all("SELECT id FROM users"))
    resp = client.post(
        "/register",
        data={"name": "Eve", "email": "eve@example.com", "password": "secret123"},
    )
    assert resp.status_code == 302
    assert len(fetch_all("SELECT id FROM users")) == before
